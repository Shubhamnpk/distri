export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

export function companySlug(c: Company): string {
  return slugify(c.name)
}

export function projectSlug(p: Project): string {
  return slugify(p.name)
}

